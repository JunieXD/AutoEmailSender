//! Non-secret object values retained independently of their display labels.

use serde::Serialize;
use ts_rs::TS;

#[derive(Clone, PartialEq, Serialize, TS)]
#[serde(
    tag = "kind",
    content = "value",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum Original {
    Task {
        id: i64,
        name: String,
        state: String,
        kind: String,
        writer: String,
        model_config_id: Option<i64>,
        template_id: Option<i64>,
        template_subject: Option<String>,
        template_body_md: Option<String>,
        generation_paused_at: Option<i64>,
        generation_pause_reason: Option<String>,
        materials: Vec<(i64, String)>,
        schedule: String,
        window_dates: Option<String>,
        window_start: Option<String>,
        window_end: Option<String>,
        per_window: Option<i64>,
    },
    Mailbox {
        id: i64,
        address: String,
        sender_name: String,
        provider: String,
        smtp_host: String,
        smtp_port: i64,
        smtp_security: String,
        imap_host: String,
        imap_port: i64,
        imap_security: String,
        daily_limit: i64,
        min_interval_s: i64,
        rotation_order: i64,
        paused_until: Option<i64>,
        pause_reason: Option<String>,
    },
    Model {
        id: i64,
        name: Option<String>,
        model: String,
        provider: String,
        base_url: Option<String>,
        agreed: i64,
        input_price: Option<f64>,
        output_price: Option<f64>,
        tasks: i64,
        crawls: i64,
    },
    Mentor {
        id: i64,
        updated_at: i64,
        trashed_at: Option<i64>,
        mailbox_id: Option<i64>,
        emails: i64,
        messages: i64,
        todos: i64,
        tags: i64,
        updates: i64,
    },
    Template {
        id: i64,
        name: String,
        subject: String,
        body_md: String,
        updated_at: i64,
    },
    Material {
        id: i64,
        file_name: String,
        size: i64,
        created_at: i64,
        for_matching: i64,
        for_writing: i64,
        attach_by_default: i64,
        emails: i64,
        tasks: i64,
    },
    Crawl {
        id: i64,
        university: Option<String>,
        school: Option<String>,
        state: String,
        start_urls: Option<String>,
        limits: String,
        candidates: i64,
        pages: i64,
        runs: i64,
    },
    Tag {
        id: i64,
        name: String,
        color: String,
        mentors: i64,
    },
    Todo {
        id: i64,
        mentor_id: i64,
        message_id: Option<i64>,
        text: String,
        due_date: Option<String>,
        due_time: Option<String>,
        done_at: Option<i64>,
    },
}
